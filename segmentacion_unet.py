def generar_video_respaldo(ruta="video_entrada.mp4", total_frames=160, size=128):
    if os.path.exists(ruta):
        print(f"Archivo '{ruta}' detectado en disco. Se usará este video.")
        return
    fourcc = cv2.VideoWriter_fourcc(*'mp4v')
    out = cv2.VideoWriter(ruta, fourcc, 20.0, (size, size), isColor=False)
    rng = np.random.default_rng(42)
    for t in range(total_frames):
        frame = rng.normal(45, 12, (size, size)).astype(np.float32)
        cx = int(64 + 22 * np.sin(t * 0.08))
        cy = int(64 + 18 * np.cos(t * 0.06))
        rx = int(22 + 4 * np.sin(t * 0.12))
        ry = int(16 + 3 * np.cos(t * 0.10))
        mask_temp = np.zeros((size, size), dtype=np.uint8)
        cv2.ellipse(mask_temp, (cx, cy), (rx, ry), t * 1.5, 0, 360, 255, -1)
        mask_blur = cv2.GaussianBlur(mask_temp.astype(np.float32), (7, 7), 0)
        frame = np.clip(frame + (mask_blur / 255.0) * 145.0, 0, 255).astype(np.uint8)
        out.write(frame)
    out.release()
    print(f"Video sintético generado correctamente en '{ruta}' ({total_frames} fotogramas).")

