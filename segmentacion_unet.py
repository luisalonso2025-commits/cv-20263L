def cargar_dataset_video(ruta_video, offset, umbral, num_frames=120, img_size=128):
    cap = cv2.VideoCapture(ruta_video)
    assert cap.isOpened(), f"No se pudo abrir el video: {ruta_video}"

    X_list, Y_list = [], []
    kernel = np.ones((5, 5), np.uint8)

    # Avanzar 'offset' fotogramas
    cap.set(cv2.CAP_PROP_POS_FRAMES, offset)

    while len(X_list) < num_frames:
        ret, frame = cap.read()
        if not ret:
            break

        # Convertir a escala de grises si tiene 3 canales
        if len(frame.shape) == 3:
            frame = cv2.cvtColor(frame, cv2.COLOR_BGR2GRAY)

        # Redimensionar a (img_size, img_size)
        frame_resized = cv2.resize(frame, (img_size, img_size), interpolation=cv2.INTER_AREA)

        # Crear máscara binaria (0 o 255) y aplicar cierre morfológico
        mask = np.where(frame_resized >= umbral, 255, 0).astype(np.uint8)
        mask_closed = cv2.morphologyEx(mask, cv2.MORPH_CLOSE, kernel)

        # Normalizar X a [0, 1] y Y a {0.0, 1.0}
        X_list.append(frame_resized.astype(np.float32) / 255.0)
        Y_list.append((mask_closed > 0).astype(np.float32))

    cap.release()
    X = np.array(X_list, dtype=np.float32)[:, None, :, :]
    Y = np.array(Y_list, dtype=np.float32)[:, None, :, :]
    return X, Y

