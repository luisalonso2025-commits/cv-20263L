"""Parte 3: Pérdida Híbrida (BCE + Dice) y Entrenamiento"""

def dice_coefficient(logits, targets, smooth=1e-6):
    probs = torch.sigmoid(logits)
    # Aplanar por muestra del batch para promediar correctamente
    probs_flat = probs.view(probs.size(0), -1)
    targets_flat = targets.view(targets.size(0), -1)

    intersection = (probs_flat * targets_flat).sum(dim=1)
    union = probs_flat.sum(dim=1) + targets_flat.sum(dim=1)

    dice = (2.0 * intersection + smooth) / (union + smooth)
    return dice.mean()

def hybrid_loss(logits, targets, alpha=ALPHA):
    bce = nn.BCEWithLogitsLoss()(logits, targets)
    dice = dice_coefficient(logits, targets)
    return alpha * bce + (1.0 - alpha) * (1.0 - dice)

def entrenar_modelo(model, train_loader, val_loader, epochs=20, lr=1e-3):
    optimizer = optim.Adam(model.parameters(), lr=lr)
    historial = {'train_loss': [], 'val_dice': []}

    for epoch in range(epochs):
        model.train()
        running_loss = 0.0
        for x_b, y_b in train_loader:
            x_b, y_b = x_b.to(device), y_b.to(device)
            optimizer.zero_grad()
            logits = model(x_b)
            loss = hybrid_loss(logits, y_b, alpha=ALPHA)
            loss.backward()
            optimizer.step()
            running_loss += loss.item() * x_b.size(0)

        epoch_loss = running_loss / len(train_loader.dataset)

        # Evaluación en validación
        model.eval()
        val_dice_total = 0.0
        with torch.no_grad():
            for x_v, y_v in val_loader:
                x_v, y_v = x_v.to(device), y_v.to(device)
                logits_v = model(x_v)
                val_dice_total += dice_coefficient(logits_v, y_v).item() * x_v.size(0)

        epoch_dice = val_dice_total / len(val_loader.dataset)
        historial['train_loss'].append(epoch_loss)
        historial['val_dice'].append(epoch_dice)
        print(f"Época {epoch+1:02d}/{epochs} | Train Loss: {epoch_loss:.4f} | Val Dice: {epoch_dice:.4f}")

    return historial

