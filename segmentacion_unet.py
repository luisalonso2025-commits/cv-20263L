"""Parte 2: Construcción de la Arquitectura U-Net desde Cero"""

class DoubleConv(nn.Module):
    def __init__(self, in_ch, out_ch):
        super().__init__()
        self.net = nn.Sequential(
            nn.Conv2d(in_ch, out_ch, kernel_size=3, padding=1, bias=False),
            nn.BatchNorm2d(out_ch),
            nn.ReLU(inplace=True),
            nn.Conv2d(out_ch, out_ch, kernel_size=3, padding=1, bias=False),
            nn.BatchNorm2d(out_ch),
            nn.ReLU(inplace=True)
        )

    def forward(self, x):
        return self.net(x)


class UNetPersonalizada(nn.Module):
    def __init__(self, base_ch=BASE_CH, use_skip=True):
        super().__init__()
        self.use_skip = use_skip

        # Encoder (3 niveles: 128 -> 64 -> 32 -> 16)
        self.enc1 = DoubleConv(1, base_ch)
        self.enc2 = DoubleConv(base_ch, base_ch * 2)
        self.enc3 = DoubleConv(base_ch * 2, base_ch * 4)
        self.pool = nn.MaxPool2d(2)

        # Bottleneck (resolución 16x16)
        self.bottleneck = DoubleConv(base_ch * 4, base_ch * 8)

        # Decoder (3 niveles de sobremuestreo + concatenación)
        self.up3 = nn.ConvTranspose2d(base_ch * 8, base_ch * 4, kernel_size=2, stride=2)
        self.dec3 = DoubleConv(base_ch * 8, base_ch * 4)

        self.up2 = nn.ConvTranspose2d(base_ch * 4, base_ch * 2, kernel_size=2, stride=2)
        self.dec2 = DoubleConv(base_ch * 4, base_ch * 2)

        self.up1 = nn.ConvTranspose2d(base_ch * 2, base_ch, kernel_size=2, stride=2)
        self.dec1 = DoubleConv(base_ch * 2, base_ch)

        # Salida de logits crudos (1 canal, sin Sigmoid)
        self.out_conv = nn.Conv2d(base_ch, 1, kernel_size=1)

    def forward(self, x):
        # Contracción
        s1 = self.enc1(x)              # [B, base_ch, 128, 128]
        s2 = self.enc2(self.pool(s1))  # [B, base_ch*2, 64, 64]
        s3 = self.enc3(self.pool(s2))  # [B, base_ch*4, 32, 32]

        # Cuello de botella
        b = self.bottleneck(self.pool(s3)) # [B, base_ch*8, 16, 16]

        # Interruptor de sabotaje a las skip connections
        if not self.use_skip:
            s1 = torch.zeros_like(s1)
            s2 = torch.zeros_like(s2)
            s3 = torch.zeros_like(s3)

        # Expansión
        d3 = self.up3(b)
        d3 = self.dec3(torch.cat([d3, s3], dim=1))

        d2 = self.up2(d3)
        d2 = self.dec2(torch.cat([d2, s2], dim=1))

        d1 = self.up1(d2)
        d1 = self.dec1(torch.cat([d1, s1], dim=1))

        return self.out_conv(d1)

